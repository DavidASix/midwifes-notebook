import { readdir, writeFile } from "node:fs/promises";

const drizzleDirectory = new URL("../drizzle/", import.meta.url);
const manifestPath = new URL("migrations.js", drizzleDirectory);

// Metro cannot discover SQL migrations dynamically. Generate static imports after
// Drizzle Kit runs so every migration is included in the application bundle.
// Drizzle's migrator addresses each file as mXXXX, matching its journal index.
const migrations = (await readdir(drizzleDirectory))
  .map((file) => ({ file, id: file.match(/^(\d{4})_.+\.sql$/)?.[1] }))
  .filter(({ id }) => id)
  .sort((a, b) => a.file.localeCompare(b.file));

if (migrations.length === 0) {
  throw new Error("No generated SQL migrations found in apps/mobile/drizzle.");
}

const imports = migrations
  .map(({ file, id }) => `import m${id} from ${JSON.stringify(`./${file}`)};`)
  .join("\n");
const entries = migrations.map(({ id }) => `    m${id},`).join("\n");

const manifest = `// Generated by scripts/generate-migrations-manifest.mjs. Do not edit manually.
import journal from "./meta/_journal.json";
${imports}

export default {
  journal,
  migrations: {
${entries}
  },
};
`;

await writeFile(manifestPath, manifest);
console.log(
  `Generated migration manifest for ${migrations.length} migration(s).`,
);
